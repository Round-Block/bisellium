// Renders docs/ARCHITECTURE.md into bisellium-architecture.html using the
// dossier's head.html styles. Mermaid fences become <pre class="mermaid">,
// which the artifact runtime renders natively — no library. Kept because
// every architecture republish repeats this exact transform (invoked by
// build.sh; never hand-edit the built page).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const [,, srcArg, outArg, titleArg, eyebrowArg, thesisArg] = process.argv;
const SRC = srcArg ?? "../../ARCHITECTURE.md";
const OUT = outArg ?? "bisellium-architecture.html";
const TITLE = titleArg ?? "Bisellium Architecture";
const EYEBROW = eyebrowArg ?? "Agent studio &middot; system map";
const THESIS = thesisArg ?? 'The system as it stands in the tree \u2014 module graph generated by <code>scripts/arch-graph.mjs</code>, kept current per cascade by the design lex. The model and plan live in the <a href="https://claude.ai/code/artifact/d70aefcf-d87a-4918-933f-cc7b58410d4c">dossier</a>.';
const md = readFileSync(join(here, SRC), "utf8")
  .replace(/^---\n[\s\S]*?\n---\n/, ""); // registry front matter is repo metadata, not page content

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const inline = (s) =>
  esc(s)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");

const out = [];
const lines = md.split("\n");
let i = 0, list = false, para = [];
const flushPara = () => { if (para.length) { out.push(`<p>${inline(para.join(" "))}</p>`); para = []; } };
const flushList = () => { if (list) { out.push("</ul>"); list = false; } };
while (i < lines.length) {
  const l = lines[i];
  if (l.startsWith("```")) {
    flushPara(); flushList();
    const kind = l.slice(3).trim();
    const body = [];
    i++;
    while (i < lines.length && !lines[i].startsWith("```")) body.push(lines[i++]);
    i++; // closing fence
    if (kind === "mermaid") out.push(`<pre class="mermaid">\n${body.join("\n")}\n</pre>`);
    else out.push(`<pre>${esc(body.join("\n"))}</pre>`);
    continue;
  }
  if (/^#{1,3} /.test(l)) {
    flushPara(); flushList();
    const level = l.match(/^#+/)[0].length;
    out.push(`<h${level}>${inline(l.replace(/^#+ /, ""))}</h${level}>`);
  } else if (/^[-*] /.test(l)) {
    flushPara();
    if (!list) { out.push("<ul>"); list = true; }
    out.push(`<li>${inline(l.replace(/^[-*] /, ""))}</li>`);
  } else if (l.trim() === "") {
    flushPara(); flushList();
  } else {
    para.push(l.trim());
  }
  i++;
}
flushPara(); flushList();

const head = readFileSync(join(here, "head.html"), "utf8")
  .replace("<title>Bisellium Dossier</title>", `<title>${TITLE}</title>`);
const page = `${head}<div class="wrap">

<header class="masthead">
  <p class="eyebrow">${EYEBROW}</p>
  <h1>${TITLE}</h1>
  <p class="thesis">${THESIS}</p>
</header>

<section>
${out.join("\n")}
</section>

</div>
<style>pre.mermaid{background:var(--surface);color:var(--ink);border:1px solid var(--line);overflow-x:auto}</style>
`;
writeFileSync(join(here, OUT), page);
console.log("built " + OUT);
